CREATE TABLE IF NOT EXISTS quote_samples (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fetched_at TIMESTAMP WITH TIME ZONE NOT NULL,
    cycle INTEGER NOT NULL CHECK (cycle >= 0),
    sample_index INTEGER NOT NULL CHECK (sample_index >= 0 AND sample_index < 390),
    market_time VARCHAR(5) NOT NULL,
    symbol VARCHAR(8) NOT NULL CHECK (symbol IN ('AAPL', 'GOOG', 'NVDA')),
    price DECIMAL(12,4) NOT NULL CHECK (price > 0)
);
CREATE TABLE IF NOT EXISTS users (
    id BIGINT PRIMARY KEY,
    name VARCHAR(80) NOT NULL
);
CREATE TABLE IF NOT EXISTS portfolio_holdings (
    user_id BIGINT NOT NULL,
    symbol VARCHAR(8) NOT NULL CHECK (symbol IN ('AAPL', 'GOOG', 'NVDA')),
    quantity DECIMAL(19,6) NOT NULL CHECK (quantity > 0),
    PRIMARY KEY (user_id, symbol),
    FOREIGN KEY (user_id) REFERENCES users(id)
);
CREATE TABLE IF NOT EXISTS portfolio_seed (
    id INTEGER PRIMARY KEY CHECK (id = 1),
    user_count INTEGER NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_quote_samples_symbol_id ON quote_samples(symbol,id);
